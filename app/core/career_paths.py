def build_match_explanation(recommendation: dict) -> str:
    """
    Build a student-specific explanation using SHAP information
    stored with the ML recommendation.

    Supports both the current ML naming and the existing
    saved recommendation naming.
    """

    shap_weights = (
        recommendation.get("shap_feature_weights")
        or recommendation.get("shap_weights")
        or []
    )

    positive_features = []

    for item in shap_weights:
        feature = item.get("feature")

        impact = item.get(
            "shap_contribution",
            item.get("impact", 0)
        )

        try:
            impact = float(impact)
        except (TypeError, ValueError):
            impact = 0

        if feature and impact > 0:
            positive_features.append(
                (feature, impact)
            )

    positive_features.sort(
        key=lambda x: x[1],
        reverse=True
    )

    top_features = positive_features[:3]

    if not top_features:
        return (
            "This career direction was selected from "
            "your overall assessment profile."
        )

    labels = [
        FEATURE_LABELS.get(feature, feature)
        for feature, _ in top_features
    ]

    if len(labels) == 1:
        factor_text = labels[0]

    elif len(labels) == 2:
        factor_text = f"{labels[0]} and {labels[1]}"

    else:
        factor_text = (
            f"{labels[0]}, {labels[1]}, and {labels[2]}"
        )

    return (
        f"This career direction was influenced by "
        f"your strengths and interests in {factor_text}."
    )



