def get_pathway_knowledge(
    career_field: str
) -> Optional[Dict[str, Any]]:
    if not career_field:
        return None

    cleaned_name = career_field.strip()

    # Exact career-field match first.
    if cleaned_name in PATHWAY_KNOWLEDGE:
        return PATHWAY_KNOWLEDGE[cleaned_name]

    # Explicit alias match second.
    alias_key = cleaned_name.lower()
    canonical_name = PATHWAY_ALIASES.get(alias_key)

    if canonical_name:
        return PATHWAY_KNOWLEDGE.get(canonical_name)

    return None